#!/usr/bin/env node
// Bundles the npm packages plugins use into single ESM files they import relatively. Orca plugins
// ship without node_modules and their frames load no bare imports, so these bundles are committed.
import { readFile } from 'node:fs/promises'
import { build } from 'esbuild'

const BUNDLES = [
  {
    out: 'plugins/script-runner/vendor/yaml.mjs',
    packages: ['yaml'],
    contents: "export { parse } from 'yaml'"
  },
  {
    out: 'plugins/worktree-notes/vendor/tiptap.mjs',
    packages: [
      '@tiptap/core',
      '@tiptap/starter-kit',
      '@tiptap/markdown',
      '@tiptap/extension-list',
      '@tiptap/extensions'
    ],
    contents: [
      "export { Editor } from '@tiptap/core'",
      "export { StarterKit } from '@tiptap/starter-kit'",
      "export { Markdown } from '@tiptap/markdown'",
      "export { TaskList, TaskItem } from '@tiptap/extension-list'",
      "export { Placeholder } from '@tiptap/extensions'"
    ].join('\n')
  }
]

async function describe(name) {
  const { version, license } = JSON.parse(
    await readFile(`node_modules/${name}/package.json`, 'utf8')
  )
  return `${name} ${version} (${license})`
}

for (const bundle of BUNDLES) {
  const names = (await Promise.all(bundle.packages.map(describe))).join(', ')
  await build({
    stdin: { contents: bundle.contents, resolveDir: process.cwd() },
    bundle: true,
    format: 'esm',
    platform: 'neutral',
    mainFields: ['module', 'main'],
    minify: true,
    legalComments: 'inline',
    banner: { js: `// ${names}. Generated by scripts/vendor.mjs; do not edit.` },
    outfile: bundle.out
  })
  console.log(`wrote ${bundle.out}: ${names}`)
}
